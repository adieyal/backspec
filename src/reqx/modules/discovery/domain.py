"""Which files are read, and why the others are not. Every file ends in exactly one state."""
from __future__ import annotations

from dataclasses import dataclass
from functools import lru_cache
from typing import Literal

import pathspec

from reqx.kernel.text import sha256

DEFAULT_EXCLUDES = [
    ".git/", "node_modules/", ".venv/", "venv/", "vendor/", "dist/", "build/", "__pycache__/",
    "*.lock", "package-lock.json", "*.min.js", "*.map", ".env*", "*.pem", "*.key",
    "*.png", "*.jpg", "*.jpeg", "*.gif", "*.ico", "*.pdf", "*.woff", "*.woff2", "*.zip",
    "/reqx.capabilities.yaml", "/reqx.review.yaml",   # reqx's own files are never read as source
]
MAX_BYTES = 1_000_000
GENERATED_MARKERS = ("DO NOT EDIT", "@generated", "Code generated by")

Reason = Literal["default_exclude", "not_included", "exclude_pattern",
                 "binary", "too_large", "not_utf8", "generated"]


@dataclass(frozen=True)
class SourceFile:
    """A file as it was when the run started. Every later stage reads this, never the disk."""
    path: str
    text: str
    source_hash: str

    @property
    def lines(self) -> list[str]:
        return self.text.split("\n")


@dataclass(frozen=True)
class Left:
    """A file that was not read, with the state it ended in and why."""
    path: str
    state: Literal["excluded", "skipped"]
    reason: Reason


@dataclass(frozen=True)
class Discovery:
    files: tuple[SourceFile, ...]
    left: tuple[Left, ...]


@lru_cache(maxsize=64)
def _compiled(patterns: tuple[str, ...]) -> pathspec.PathSpec:
    try:
        return pathspec.PathSpec.from_lines("gitignore", patterns)
    except (KeyError, LookupError):   # older pathspec knows the syntax by its former name
        return pathspec.PathSpec.from_lines("gitwildmatch", patterns)


def _spec(patterns: list[str]) -> pathspec.PathSpec:
    return _compiled(tuple(patterns))


def excluded_by_pattern(path: str, include: list[str], exclude: list[str],
                        default_excludes: bool = True) -> Reason | None:
    """Why a path is out by pattern, or None. Layers only remove: exclude wins over include."""
    if default_excludes and _spec(DEFAULT_EXCLUDES).match_file(path):
        return "default_exclude"
    if include and not _spec(include).match_file(path):
        return "not_included"
    if exclude and _spec(exclude).match_file(path):
        return "exclude_pattern"
    return None


def read_or_skip(path: str, data: bytes) -> SourceFile | Left:
    """A file's snapshot, or the reason it cannot be read as source."""
    if len(data) > MAX_BYTES:
        return Left(path, "skipped", "too_large")
    if b"\x00" in data[:8192]:
        return Left(path, "skipped", "binary")
    try:
        text = data.decode("utf-8")
    except UnicodeDecodeError:
        return Left(path, "skipped", "not_utf8")
    if any(marker in text[:600] for marker in GENERATED_MARKERS):
        return Left(path, "skipped", "generated")
    return SourceFile(path, text, sha256(text))
