from reqx.modules.discovery.domain import excluded_by_pattern, read_or_skip, Left, SourceFile
from reqx.modules.discovery.facade import DiscoveryFacade


class Repo:
    def __init__(self, files):
        self.files = files

    def list_paths(self):
        return sorted(self.files)

    def read(self, path):
        return self.files[path]


def test_exclude_wins_over_include_and_defaults_come_first():
    assert excluded_by_pattern("node_modules/a.js", [], []) == "default_exclude"
    assert excluded_by_pattern("docs/a.md", ["src/**"], []) == "not_included"
    assert excluded_by_pattern("src/gen/a.py", ["src/**"], ["**/gen/**"]) == "exclude_pattern"
    assert excluded_by_pattern("src/a.py", ["src/**"], ["**/gen/**"]) is None
    assert excluded_by_pattern("node_modules/a.js", [], [], default_excludes=False) is None


def test_a_file_that_is_not_source_is_skipped_with_its_reason():
    assert read_or_skip("a.bin", b"ab\x00cd") == Left("a.bin", "skipped", "binary")
    assert read_or_skip("a.txt", b"\xff\xfe\xfa") == Left("a.txt", "skipped", "not_utf8")
    assert read_or_skip("a.py", b"# Code generated by tool. DO NOT EDIT.\n").reason == "generated"
    assert read_or_skip("big.py", b"x" * 1_000_001).reason == "too_large"
    assert isinstance(read_or_skip("a.py", b"x = 1\n"), SourceFile)


def test_every_listed_file_ends_in_exactly_one_place():
    repo = Repo({"src/a.py": b"x = 1\n", "src/b.bin": b"\x00", ".env": b"KEY=1", "docs/r.md": b"# r\n"})
    found = DiscoveryFacade(repo).discover(include=["src/**", ".env"], exclude=[])
    read = {f.path for f in found.files}
    left = {l.path: (l.state, l.reason) for l in found.left}
    assert read == {"src/a.py"}
    assert left == {"src/b.bin": ("skipped", "binary"), ".env": ("excluded", "default_exclude"),
                    "docs/r.md": ("excluded", "not_included")}
    assert len(read) + len(left) == 4
